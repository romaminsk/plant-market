#!/usr/bin/env bash
set -euo pipefail
IFS=$'\n\t'

cd "$(dirname "$0")/.."

FORCE=0
if [[ "${1:-}" == "--force" ]]; then
  FORCE=1
fi

DOMAIN="${STAGING_DOMAIN:-staging.localhost}"
TLS_MODE="${STAGING_TLS:-internal}"
ACME_EMAIL="${ACME_EMAIL:-}"
if [[ "$TLS_MODE" == "acme" ]]; then
  TLS_VALUE="${ACME_EMAIL:?ACME_EMAIL is required when STAGING_TLS=acme}"
else
  TLS_VALUE="internal"
fi
SECRETS_DIR="infra/staging/secrets"
ENV_FILE=".env.staging"
SEAWEED_CONFIG="infra/staging/seaweedfs-s3.json"

mkdir -p "$SECRETS_DIR"
umask 077

write_secret() {
  local name="$1"
  local file="$SECRETS_DIR/$name.txt"
  if [[ "$FORCE" -eq 1 || ! -s "$file" ]]; then
    openssl rand -base64 48 | tr -d '\n' > "$file"
  fi
  chmod 600 "$file"
}

write_secret postgres_password
write_secret jwt_secret
write_secret payment_webhook_secret

if [[ "$FORCE" -eq 1 || ! -f "$ENV_FILE" ]]; then
  S3_SECRET_KEY="$(openssl rand -base64 32 | tr -d '\n')"
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/staging-init.sh. Do not commit.
STAGING_DOMAIN=$DOMAIN
STAGING_TLS=$TLS_MODE
STAGING_TLS_VALUE=$TLS_VALUE
ACME_EMAIL=$ACME_EMAIL
APP_ENV=staging

POSTGRES_USER=plantmarket
# Placeholder for compose interpolation; the real value comes from /run/secrets.
POSTGRES_PASSWORD=secret-from-file
JWT_SECRET=secret-from-file
PAYMENT_WEBHOOK_SECRET=secret-from-file

JWT_ISSUER=https://$DOMAIN
SESSION_COOKIE_NAME=__Host-PM-SESSION
SESSION_COOKIE_SECURE=true
CORS_ALLOWED_ORIGINS=https://$DOMAIN,https://admin.$DOMAIN

NEXT_PUBLIC_API_URL=https://$DOMAIN
NEXT_PUBLIC_SITE_URL=https://$DOMAIN
VITE_API_URL=https://$DOMAIN

MEDIA_PUBLIC_BASE_URL=https://$DOMAIN/media
MEDIA_STORAGE=s3
S3_REGION=us-east-1
S3_BUCKET=plant-market-media
S3_ACCESS_KEY=plantmarket
S3_SECRET_KEY=$S3_SECRET_KEY

RATE_LIMIT_REDIS_URL=redis://redis:6379
EOF
  cat > "$SEAWEED_CONFIG" <<EOF
{
  "identities": [
    {
      "name": "plantmarket",
      "credentials": [{"accessKey": "plantmarket", "secretKey": "$S3_SECRET_KEY"}],
      "actions": ["Admin", "Read", "Write", "List", "Tagging"]
    }
  ]
}
EOF
  chmod 600 "$ENV_FILE" "$SEAWEED_CONFIG"
  echo "Wrote $ENV_FILE, $SEAWEED_CONFIG and $SECRETS_DIR/*.txt"
else
  echo "Keeping existing $ENV_FILE; use --force to rotate"
fi

cat <<EOF

Staging config ready for https://$DOMAIN and https://admin.$DOMAIN (TLS: $TLS_MODE).
Start:
  docker compose -f docker-compose.yml -f docker-compose.staging.yml --env-file .env.staging up -d --build --wait
Trust the local CA or use curl -k:
  docker compose -f docker-compose.yml -f docker-compose.staging.yml --env-file .env.staging exec caddy cat /data/caddy/pki/authorities/local/root.crt > /tmp/plant-market-ca.crt
EOF
