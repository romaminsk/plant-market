/**
 * Data-driven UI matrix: 100 cases live in {@code src/test/resources/ui-cases.json}.
 *
 * <p>The catalog is generated by {@code scripts/generate-ui-cases.py}; the human-readable catalog
 * is {@code docs/test-cases.md}. Cases share one browser context and reset cookies/localStorage
 * before each run, which keeps the whole matrix under a few minutes.
 */
@Feature("UI matrix")
@EnabledIfEnvironmentVariable(named = "E2E_BASE_URL", matches = ".+")
class UiMatrixE2ETest {

  private static final ObjectMapper MAPPER = new ObjectMapper();
  private static final HttpClient HTTP = HttpClient.newHttpClient();
  private static final String A11Y_JS =
      """
      () => {
        const problems = [];
        if (document.documentElement.lang !== 'ru') problems.push('lang');
        if (document.querySelectorAll('h1').length !== 1) problems.push('h1');
        for (const img of document.querySelectorAll('img')) {
          if (!img.hasAttribute('alt')) problems.push('img-alt:' + img.src);
        }
        for (const el of document.querySelectorAll('input:not([type=hidden]), select, textarea')) {
          const labeled =
            (el.labels && el.labels.length > 0) ||
            el.getAttribute('aria-label') ||
            el.getAttribute('title');
          if (!labeled) problems.push('label:' + (el.name || el.id));
        }
        return problems;
      }
      """;

  private static Playwright playwright;
  private static Browser browser;
  private static BrowserContext context;
  private static Page page;
  private static JsonNode cases;
  private static String baseUrl;
  private static String adminUrl;
  private static String apiUrl;
  private static String adminToken;
  private static Map<String, String> placeholders;
  private static int lastStatus;
  private static String currentId = "";

  @BeforeAll
  static void setUp() throws Exception {
    baseUrl = env("E2E_BASE_URL", "http://localhost:3000");
    adminUrl = env("E2E_ADMIN_URL", "http://localhost:5173");
    apiUrl = env("E2E_API_URL", "http://localhost:8080");

    playwright = Playwright.create();
    browser = playwright.chromium().launch(new BrowserType.LaunchOptions().setHeadless(true));
    context = browser.newContext(new Browser.NewContextOptions().setViewportSize(1280, 800));
    context.setDefaultTimeout(45_000);
    context.setDefaultNavigationTimeout(60_000);
    page = context.newPage();

    try (InputStream input = UiMatrixE2ETest.class.getResourceAsStream("/ui-cases.json")) {
      assertThat(input).as("ui-cases.json is on the test classpath").isNotNull();
      cases = MAPPER.readTree(new String(input.readAllBytes(), StandardCharsets.UTF_8));
    }

    adminToken = ApiTokens.admin(apiUrl);
    placeholders = new HashMap<>();
    placeholders.put("productId", SeedData.productId(apiUrl, "MON-001"));
    JsonNode plants = getJson("/api/v1/individual-plants?status=AVAILABLE&size=50").path("items");
    JsonNode plant = null;
    for (JsonNode item : plants) {
      if ("IP-001".equals(item.path("code").asString())) {
        plant = item;
        break;
      }
    }
    if (plant == null && plants.size() > 0) {
      plant = plants.get(0);
    }
    assertThat(plant).as("at least one available individual plant").isNotNull();
    placeholders.put("plantId", plant.path("id").asString());
    placeholders.put("plantName", plant.path("productName").asString());
    placeholders.put(
        "plantPrice",
        String.format(Locale.ROOT, "%.2f", plant.path("priceMinor").asInt() / 100.0)
            .replace('.', ','));
  }

  @AfterAll
  static void tearDown() {
    if (context != null) {
      context.close();
    }
    if (browser != null) {
      browser.close();
    }
    if (playwright != null) {
      playwright.close();
    }
  }

  @TestFactory
  Stream<DynamicTest> uiMatrix() {
    List<DynamicTest> tests = new ArrayList<>();
    for (JsonNode entry : cases.path("cases")) {
      String name = entry.path("id").asString() + " · " + entry.path("name").asString();
      tests.add(DynamicTest.dynamicTest(name, () -> runCase(entry)));
    }
    return tests.stream();
  }

  private void runCase(JsonNode entry) throws Exception {
    currentId = entry.path("id").asString();
    try {
      reset(entry);
      for (JsonNode step : entry.path("steps")) {
        execute(step);
      }
    } catch (Throwable failure) {
      Path directory = Path.of("build", "e2e-artifacts", "ui-matrix");
      Files.createDirectories(directory);
      try {
        page.screenshot(
            new Page.ScreenshotOptions()
                .setPath(directory.resolve(currentId + ".png"))
                .setFullPage(true));
      } catch (RuntimeException ignored) {
        // The screenshot is best-effort; the assertion failure is the useful artifact.
      }
      throw failure;
    } finally {
      page.setViewportSize(1280, 800);
    }
  }

  private void reset(JsonNode entry) throws Exception {
    context.clearCookies();
    JsonNode viewport = entry.path("viewport");
    if (viewport.isArray() && viewport.size() == 2) {
      page.setViewportSize(viewport.get(0).asInt(), viewport.get(1).asInt());
    } else {
      page.setViewportSize(1280, 800);
    }

    page.navigate(baseUrl);
    page.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }");
    page.navigate(adminUrl);
    page.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }");

    if (entry.path("admin").asBoolean(false)) {
      // Access tokens live 10 minutes; the matrix runs longer, so mint a fresh one per admin case.
      adminToken = ApiTokens.freshAdmin(apiUrl);
      context.addCookies(
          List.of(
              new Cookie("pm.admin.access", adminToken)
                  .setDomain("localhost")
                  .setPath("/")
                  .setHttpOnly(true)
                  .setSameSite(SameSiteAttribute.STRICT)));
      page.reload();
      page.getByRole(AriaRole.HEADING, new Page.GetByRoleOptions().setName("Продукты")).waitFor();
      lastStatus = 200;
      return;
    }

    JsonNode storage = entry.path("storage");
    if (storage.isObject()) {
      page.navigate(baseUrl);
      for (var field : storage.properties()) {
        page.evaluate(
            "([key, value]) => localStorage.setItem(key, value)",
            List.of(field.getKey(), resolve(field.getValue().asString())));
      }
    }

    String start = entry.path("start").asString();
    String target =
        "admin".equals(entry.path("area").asString()) ? adminUrl + start : resolve(start);
    Response response = page.navigate(target);
    lastStatus = response == null ? 0 : response.status();
  }

  private void execute(JsonNode step) {
    String action = step.path("action").asString();
    String selector = step.path("selector").asString("");
    String value = resolve(step.path("value").asString(""));
    switch (action) {
      case "expectStatus" -> assertThat(lastStatus).isEqualTo(step.path("value").asInt());
      case "expectText" -> assertThat(page.locator("body").innerText()).contains(value);
      case "expectTextGone" -> assertThat(page.locator("body").innerText()).doesNotContain(value);
      case "expectCount" ->
          assertThat(page.locator(selector).count()).isEqualTo(step.path("value").asInt());
      case "expectMinCount" ->
          assertThat(page.locator(selector).count())
              .isGreaterThanOrEqualTo(step.path("value").asInt());
      case "expectVisible" ->
          page.locator(selector)
              .first()
              .waitFor(
                  new com.microsoft.playwright.Locator.WaitForOptions()
                      .setState(WaitForSelectorState.VISIBLE));
      case "expectHidden" ->
          page.locator(selector)
              .first()
              .waitFor(
                  new com.microsoft.playwright.Locator.WaitForOptions()
                      .setState(WaitForSelectorState.HIDDEN));
      case "expectAttribute" -> expectAttribute(step, selector);
      case "expectUrl" -> assertThat(page.url()).contains(value);
      case "waitUrl" -> page.waitForURL("**" + value);
      case "expectTitle" -> assertThat(page.title()).contains(value);
      case "expectCss" -> expectCss(step, selector);
      case "expectStorage" ->
          assertThat(page.evaluate("key => localStorage.getItem(key)", step.path("key").asString()))
              .isEqualTo(value);
      case "expectNoOverflow" ->
          assertThat(
                  (Boolean)
                      page.evaluate(
                          "() => document.documentElement.scrollWidth"
                              + " <= document.documentElement.clientWidth + 1"))
              .isTrue();
      case "expectA11y" ->
          assertThat((List<?>) page.evaluate(A11Y_JS)).as("a11y problems").isEmpty();
      case "waitText" -> page.getByText(value).first().waitFor();
      case "waitForFunction" -> page.waitForFunction(value);
      case "waitSelector" -> page.locator(selector).first().waitFor();
      case "click" -> page.locator(selector).first().click();
      case "fill" -> page.locator(selector).first().fill(value);
      case "select" ->
          page.locator(selector).first().selectOption(new SelectOption().setLabel(value));
      case "hover" -> page.locator(selector).first().hover();
      case "adminTab" ->
          page.getByRole(AriaRole.BUTTON, new Page.GetByRoleOptions().setName(value)).click();
      default -> throw new IllegalArgumentException("Unknown UI action: " + action);
    }
  }

  private void expectAttribute(JsonNode step, String selector) {
    String actual = page.locator(selector).first().getAttribute(step.path("name").asString());
    String expected = resolve(step.path("value").asString());
    String match = step.path("match").asString("equals");
    switch (match) {
      case "contains" -> assertThat(actual).contains(expected);
      case "nonEmpty" -> assertThat(actual).isNotBlank();
      default -> assertThat(actual).isEqualTo(expected);
    }
  }

  private void expectCss(JsonNode step, String selector) {
    String property = step.path("property").asString();
    String actual =
        String.valueOf(
                page.locator(selector)
                    .first()
                    .evaluate("el => getComputedStyle(el).getPropertyValue('" + property + "')"))
            .trim();
    assertThat(actual.replaceAll("\\s+", " "))
        .isEqualTo(step.path("value").asString().replaceAll("\\s+", " "));
  }

  private String resolve(String template) {
    String resolved = template;
    for (var entry : placeholders.entrySet()) {
      resolved = resolved.replace("{" + entry.getKey() + "}", entry.getValue());
    }
    if (resolved.startsWith("/")) {
      return baseUrl + resolved;
    }
    return resolved;
  }

  private static JsonNode getJson(String path) throws Exception {
    HttpResponse<String> response =
        HTTP.send(
            HttpRequest.newBuilder(URI.create(apiUrl + path)).GET().build(),
            HttpResponse.BodyHandlers.ofString());
    assertThat(response.statusCode()).as("response body: %s", response.body()).isBetween(200, 299);
    return MAPPER.readTree(response.body());
  }

  private static String env(String key, String fallback) {
    String value = System.getenv(key);
    return value == null || value.isBlank() ? fallback : value;
  }
}
