  private void executeApi(JsonNode step, Map<String, JsonNode> store) throws Exception {
    String operation = step.path("operation").asString();
    JsonNode params = step.path("params");
    JsonNode result =
        switch (operation) {
          case "createCategory" -> createCategory(params, store);
          case "createProduct" -> createProduct(params, store);
          case "createPlant" -> createPlant(params, store, false);
          case "createSoldOutPlant" -> createPlant(params, store, true);
          case "createVariant" -> createVariant(params, store);
          case "createStock" -> createStock(params, store);
          case "findPlant" -> findPlant(params);
          case "createOrder" -> createOrder(params, store);
          case "payOrder" -> payOrder(params, store);
          case "createClaim" -> createClaim(params, store);
          case "registerCustomer" -> registerCustomer(params, store);
          case "decideClaim" -> decideClaim(params, store);
          case "transitionPlant" -> transitionPlant(params, store);
          case "archiveProduct" -> archiveProduct(params);
          case "archiveVariant" -> archiveVariant(params);
          default -> throw new IllegalArgumentException("Unknown API operation: " + operation);
        };
    String storeName = step.path("store").asString("");
    if (!storeName.isBlank() && result != null) {
      store.put(storeName, result);
    }
  }

