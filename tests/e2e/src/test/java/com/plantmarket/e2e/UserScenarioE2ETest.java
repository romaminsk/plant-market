  private String resolvePath(String value) {
    return value.startsWith("/") ? baseUrl + value : value;
  }

  private String resolve(String template, Map<String, JsonNode> store) {
    if (template == null || template.isEmpty()) {
      return template;
    }
    String resolved = template.replace("{uid}", scenarioUid);
    Matcher matcher = PLACEHOLDER.matcher(resolved);
    StringBuilder builder = new StringBuilder();
    while (matcher.find()) {
      String name = matcher.group(1);
      String field = matcher.group(2);
      JsonNode entity = store.get(name);
      String replacement = "";
      if (entity != null) {
        if ("short".equals(field)) {
          String id = entity.path("id").asString();
          replacement = id.length() > 8 ? id.substring(id.length() - 8) : id;
        } else if ("shortUpper".equals(field)) {
          String id = entity.path("id").asString();
          replacement = (id.length() > 8 ? id.substring(id.length() - 8) : id).toUpperCase();
        } else {
          replacement = entity.path(field).asString("");
        }
      }
      matcher.appendReplacement(builder, Matcher.quoteReplacement(replacement));
    }
    matcher.appendTail(builder);
    return builder.toString();
  }

  private String adminToken() throws Exception {
    long now = System.currentTimeMillis();
    if (cachedAdminToken == null || now - cachedAdminAt > 8 * 60_000L) {
      cachedAdminToken = ApiTokens.freshAdmin(apiUrl);
      cachedAdminAt = now;
    }
    return cachedAdminToken;
  }

  private String customerToken() throws Exception {
    long now = System.currentTimeMillis();
    if (cachedCustomerToken == null || now - cachedCustomerAt > 8 * 60_000L) {
      cachedCustomerToken = ApiTokens.freshCustomer(apiUrl);
      cachedCustomerAt = now;
    }
    return cachedCustomerToken;
  }

  private static JsonNode getJson(String path, String token) throws Exception {
    HttpRequest.Builder builder = HttpRequest.newBuilder(URI.create(apiUrl + path)).GET();
    if (token != null) {
      builder.header("Authorization", "Bearer " + token);
    }
    HttpResponse<String> response =
        HTTP.send(builder.build(), HttpResponse.BodyHandlers.ofString());
    assertThat(response.statusCode()).as("response body: %s", response.body()).isBetween(200, 299);
    return MAPPER.readTree(response.body());
  }

  private JsonNode post(String path, String token, Object body) throws Exception {
    HttpRequest.Builder builder =
        HttpRequest.newBuilder(URI.create(apiUrl + path))
            .header("Content-Type", "application/json")
            .POST(HttpRequest.BodyPublishers.ofString(MAPPER.writeValueAsString(body)));
    if (token != null) {
      builder.header("Authorization", "Bearer " + token);
    }
    HttpResponse<String> response =
        HTTP.send(builder.build(), HttpResponse.BodyHandlers.ofString());
    assertThat(response.statusCode()).as("response body: %s", response.body()).isBetween(200, 299);
    return MAPPER.readTree(response.body());
  }

  private JsonNode delete(String path, String token) throws Exception {
    HttpResponse<String> response =
        HTTP.send(
            HttpRequest.newBuilder(URI.create(apiUrl + path))
                .header("Authorization", "Bearer " + token)
                .DELETE()
                .build(),
            HttpResponse.BodyHandlers.ofString());
    assertThat(response.statusCode()).as("response body: %s", response.body()).isBetween(200, 299);
    return MAPPER.createObjectNode();
  }

  private static String env(String key, String fallback) {
    String value = System.getenv(key);
    return value == null || value.isBlank() ? fallback : value;
  }
