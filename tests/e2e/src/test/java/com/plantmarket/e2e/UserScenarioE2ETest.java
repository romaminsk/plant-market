  @TestFactory
  Stream<DynamicTest> userScenarios() {
    String filter = System.getenv("SCENARIO_IDS");
    List<DynamicTest> tests = new ArrayList<>();
    for (JsonNode entry : scenarios.path("scenarios")) {
      String id = entry.path("id").asString();
      if (filter != null && !filter.isBlank() && !List.of(filter.split(",")).contains(id)) {
        continue;
      }
      String name = id + " · " + entry.path("name").asString();
      tests.add(
          DynamicTest.dynamicTest(
              name,
              () -> {
                try {
                  runScenario(entry);
                } catch (Throwable firstAttempt) {
                  // One retry for transient admin-list refresh races in long UI journeys.
                  runScenario(entry);
                }
              }));
    }
    return tests.stream();
  }

  private void runScenario(JsonNode entry) throws Exception {
    String id = entry.path("id").asString();
    scenarioUid = UUID.randomUUID().toString().substring(0, 8);
    String auth = entry.path("auth").asString("none");
    Map<String, JsonNode> store = new HashMap<>();
    Browser.NewContextOptions options = new Browser.NewContextOptions().setViewportSize(1280, 800);
    if ("customer".equals(auth)) {
      refreshCustomerState();
      options.setStorageState(Files.readString(customerState));
    }
    JsonNode viewport = entry.path("viewport");
    if (viewport.isArray() && viewport.size() == 2) {
      options.setViewportSize(viewport.get(0).asInt(), viewport.get(1).asInt());
    }

    BrowserContext context = browser.newContext(options);
    context.setDefaultTimeout(45_000);
    context.setDefaultNavigationTimeout(60_000);
    Page page = context.newPage();
    try {
      if ("admin".equals(auth)) {
        String token = adminToken();
        page.navigate(adminUrl);
        page.evaluate("t => localStorage.setItem('pm.admin.accessToken', t)", token);
        page.reload();
        page.getByRole(AriaRole.HEADING, new Page.GetByRoleOptions().setName("Продукты")).waitFor();
      }
      for (JsonNode step : entry.path("steps")) {
        execute(step, page, store);
      }
    } catch (Throwable failure) {
      Path directory = Path.of("build", "e2e-artifacts", "user-scenarios");
      Files.createDirectories(directory);
      try {
        page.screenshot(
            new Page.ScreenshotOptions().setPath(directory.resolve(id + ".png")).setFullPage(true));
      } catch (RuntimeException ignored) {
        // Best effort; the assertion failure is the useful artifact.
      }
      throw failure;
    } finally {
      context.close();
    }
  }

  private void execute(JsonNode step, Page page, Map<String, JsonNode> store) throws Exception {
    String action = step.path("action").asString();
    String selector = resolve(step.path("selector").asString(""), store);
    String value = resolve(step.path("value").asString(""), store);
    switch (action) {
      case "api" -> executeApi(step, store);
      case "goto" -> page.navigate(resolvePath(value));
      case "gotoAdmin" -> page.navigate(adminUrl + value);
      case "reload" -> page.reload();
      case "setCart" -> setCart(page, step.path("items"), store);
      case "acceptCookies" -> acceptCookies(page);
      case "click" -> page.locator(selector).first().click();
      case "fill" -> page.locator(selector).first().fill(value);
      case "select" ->
          page.locator(selector).first().selectOption(new SelectOption().setLabel(value));
      case "check" -> page.locator(selector).first().check();
      case "press" -> page.locator(selector).first().press(value);
      case "hover" -> page.locator(selector).first().hover();
      case "upload" -> page.locator(selector).first().setInputFiles(Path.of(value));
      case "waitText" -> page.getByText(value).first().waitFor();
      case "waitSelector" -> page.locator(selector).first().waitFor();
      case "waitUrl" -> page.waitForURL("**" + value + "**");
      case "waitForFunction" -> page.waitForFunction(value);
      case "expectText" -> assertThat(page.locator("body").innerText()).contains(value);
      case "expectTextGone" -> assertThat(page.locator("body").innerText()).doesNotContain(value);
      case "expectCount" ->
          assertThat(page.locator(selector).count()).isEqualTo(step.path("value").asInt());
      case "expectMinCount" ->
          assertThat(page.locator(selector).count())
              .isGreaterThanOrEqualTo(step.path("value").asInt());
      case "expectVisible" -> assertThat(page.locator(selector).first().isVisible()).isTrue();
      case "expectHidden" -> assertThat(page.locator(selector).first().isVisible()).isFalse();
      case "expectDisabled" -> assertThat(page.locator(selector).first().isDisabled()).isTrue();
      case "expectEnabled" -> assertThat(page.locator(selector).first().isDisabled()).isFalse();
      case "expectAttribute" -> expectAttribute(step, page, selector, store);
      case "expectInputValue" ->
          assertThat(page.locator(selector).first().inputValue()).isEqualTo(value);
      case "expectUrl" -> assertThat(page.url()).contains(value);
      case "expectTitle" -> assertThat(page.title()).contains(value);
      case "expectCss" -> expectCss(step, page, selector);
      case "expectStorage" ->
          assertThat(page.evaluate("key => localStorage.getItem(key)", step.path("key").asString()))
              .isEqualTo(value);
      case "expectPricesAligned" ->
          assertThat(
                  (Boolean)
                      page.evaluate(
                          """
                          () => {
                            const prices = [...document.querySelectorAll(
                              '.cart-list:not(.compact) .cart-item .price'
                            )];
                            if (prices.length < 2) return false;
                            const rights = prices.map((el) =>
                              Math.round(el.getBoundingClientRect().right)
                            );
                            return rights.every((right) => right === rights[0]);
                          }
                          """))
              .isTrue();
      case "expectNoOverflow" ->
          assertThat(
                  (Boolean)
                      page.evaluate(
                          "() => document.documentElement.scrollWidth"
                              + " <= document.documentElement.clientWidth + 1"))
              .isTrue();
      case "expectA11y" ->
          assertThat((List<?>) page.evaluate(A11Y_JS)).as("a11y problems").isEmpty();
      case "expectActiveTag" ->
          assertThat(
                  String.valueOf(
                      page.evaluate(
                          "() => document.activeElement && document.activeElement.tagName")))
              .isIn(List.of(value.split(",")));
      case "adminTab" ->
          page.getByRole(AriaRole.BUTTON, new Page.GetByRoleOptions().setName(value)).click();
      default -> throw new IllegalArgumentException("Unknown scenario action: " + action);
    }
  }

  private void expectAttribute(
      JsonNode step, Page page, String selector, Map<String, JsonNode> store) {
    String actual = page.locator(selector).first().getAttribute(step.path("name").asString());
    String expected = resolve(step.path("value").asString(), store);
    String match = step.path("match").asString("equals");
    switch (match) {
      case "contains" -> assertThat(actual).contains(expected);
      case "nonEmpty" -> assertThat(actual).isNotBlank();
      default -> assertThat(actual).isEqualTo(expected);
    }
  }

  private void expectCss(JsonNode step, Page page, String selector) {
    String property = step.path("property").asString();
    String actual =
        String.valueOf(
                page.locator(selector)
                    .first()
                    .evaluate("el => getComputedStyle(el).getPropertyValue('" + property + "')"))
            .trim();
    assertThat(actual.replaceAll("\\s+", " "))
        .isEqualTo(step.path("value").asString().replaceAll("\\s+", " "));
  }

